"""Generate runtime image inputs from the authoritative project lock, offline."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
import tomllib

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.ci_toolchain import TOOLCHAIN

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path('.github/docker/runtime-dependencies')
PROFILES = {'runtime': ('--no-dev',), 'wdpa': ('--no-dev', '--extra', 'wdpa-native'),
            'ci-plan': ('--only-group', 'ci-plan')}


def generate(root=ROOT):
    version = subprocess.check_output(['uv', '--version'], text=True).split()[1]
    if version != TOOLCHAIN['uv']:
        raise ValueError(f"Runtime exports require uv {TOOLCHAIN['uv']}; found {version}")
    project = tomllib.loads((root / 'pyproject.toml').read_text())
    options = project.get('tool', {}).get('uv', {})
    # These images run source modules, not an installed project. A new package
    # or installer setting needs an explicit projection rather than silent loss.
    if 'build-system' in project or set(options) - {'extra-build-dependencies'}:
        raise ValueError('Runtime exports need explicit support for new project/build settings')
    builds = options.get('extra-build-dependencies', {})
    if any(not isinstance(value, list) or any(not isinstance(item, str) for item in value)
           for value in builds.values()):
        raise ValueError('Runtime build dependencies must be lists of requirement strings')
    config = '# Generated by scripts/runtime_dependencies.py; edit pyproject.toml.\n[pip.extra-build-dependencies]\n'
    config += ''.join(f'{json.dumps(name)} = {json.dumps(value)}\n' for name, value in sorted(builds.items()))
    result = {OUTPUT / 'uv.toml': config.encode()}
    for name, flags in PROFILES.items():
        result[OUTPUT / f'pylock.{name}.toml'] = subprocess.check_output(
            ['uv', 'export', '--locked', '--offline', '--python', TOOLCHAIN['python'], '--no-emit-project', '--no-header',
             '--format', 'pylock.toml', *flags], cwd=root)
    runtime_names = {package['name'] for package in tomllib.loads(result[OUTPUT / 'pylock.runtime.toml'].decode())['packages']}
    if {re.sub(r'[-_.]+', '-', name).lower() for name in builds} & runtime_names:
        raise ValueError('Generic runtime build settings need explicit image configuration support')
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject missing or stale generated inputs without writing')
    args = parser.parse_args(argv)
    try:
        generated = generate(ROOT)
        if args.check:
            stale = [str(path) for path, raw in generated.items()
                     if not (ROOT / path).is_file() or (ROOT / path).read_bytes() != raw]
            if stale:
                raise ValueError('Regenerate runtime inputs with uv run python scripts/runtime_dependencies.py: ' + ', '.join(stale))
        else:
            for path, raw in generated.items():
                destination = ROOT / path
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(raw)
    except (ValueError, subprocess.CalledProcessError) as error:
        print(f'Runtime dependency export failed: {error}', file=sys.stderr)
        return 1
    print('Runtime dependency inputs match the project lock.' if args.check else 'Generated runtime dependency inputs.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
